import Foundation

// Статусы сообщения.
//
// Хранятся числом ради совместимости: клиенты прошлых версий читают ту же
// колонку и незнакомые значения показывают как «отправляется». Поэтому новые
// состояния добавляются НОМЕРАМИ СВЕРХУ, а смысл старых не меняется.
enum MessageStatus {
    static let failed: Int32 = -1
    static let sending: Int32 = 0
    static let sent: Int32 = 1
    static let delivered: Int32 = 2
    static let read: Int32 = 3
    /// Режим «только напрямую», получателя рядом нет. Сообщение ждёт —
    /// это состояние ожидания, а не сбой, и через сервер оно не уйдёт.
    static let waitingForNearby: Int32 = 4
}
