import CoreGraphics

// Единая шкала скруглений. Радиус выбирается по РОЛИ элемента, а не на глаз:
// до этого по приложению разъехались 13 разных значений (5,7,8,9,10,12,14,16,
// 18,20,21,22,24), и соседние блоки скруглялись по-разному без всякой причины.
//
// Шкала намеренно короткая — четыре ступени. Чем меньше элемент вложен, тем
// больше радиус: вложенный блок с радиусом родителя выглядит так, будто углы
// «спорят» (концентричность), поэтому ступени идут сверху вниз по вложенности.
//
// ВАЖНО, что сюда НЕ входит: скругления мелких фигур фиксированного размера —
// глифов (стоп-квадрат 17×17), иконочных плиток настроек (28×28) и миниатюр
// (34×34). Там радиус пропорционален собственному размеру фигуры (~0.25 от
// стороны, как у системных squircle-иконок); подстановка общего радиуса
// превратила бы их в кляксы. Такие места оставлены числами намеренно.
enum Radius {
    /// Вложенные блоки внутри карточки или пузыря: цитата ответа, чип, ячейка
    /// в сетке-пикере.
    static let nested: CGFloat = 10

    /// Карточки, строки-плитки, превью медиа.
    static let card: CGFloat = 14

    /// Кнопки, поля ввода, баннеры, пузыри сообщений.
    static let control: CGFloat = 18

    /// Панели, «острова», модальные листы и стеклянные контейнеры — всё, что
    /// лежит поверх фона целым блоком.
    static let panel: CGFloat = 22
}
